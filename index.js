// ────────────────────── ⚙️ 头部配置区 (可调参数) ──────────────────────
// 🎲 调试日志总开关 (控制宿主端是否在控制台输出激活/注销日志): False/True
const 调试_日志开关 = true;

// 🏷️ 插件唯一标识符常量
const 插件_标识 = "dsh-plugin-search-plugins";

/**
 * 🛠️ 统一调试日志打印工具函数
 * 
 * 💡 逻辑解释:
 *   1. 检查头部变量 调试_日志开关 是否开启。
 *   2. 若为 True，统一附带 🏷️ 插件标识 前缀输出信息，方便排查定位。
 * 
 * 🎯 为什么这样写:
 *   杜绝在多处重复编写 console.log 判断逻辑，统一管理日志格式。
 * 
 * @param {string} 日志_文本 需打印的信息
 */
function 打印_调试日志(日志_文本) {
  if (调试_日志开关) {
    console.log(`[${插件_标识}] 💻 ${日志_文本}`);
  }
}

// ────────────────────── 🚀 插件导出契约 ──────────────────────

export const name = 插件_标识;

/**
 * 📌 插件生命周期入口函数 (apply)
 * 
 * 📊 数据结构设计图:
 * ┌───────────────────────────┐
 * │   Cordis Context (宿主)   │
 * └─────────────┬─────────────┘
 *               │ ctx.effect() 注册资源生命周期
 *               ▼
 * ┌───────────────────────────┐
 * │   注册清理函数 (Disposer)   │ ──卸载时自动触发──► 打印注销日志，回收资源
 * └───────────────────────────┘
 * 
 * 💡 逐行逻辑解释:
 *   第 1 行: 接收 Cordis 上下文对象 ctx 和配置对象 配置_选项。
 *   第 2 行: 打印插件激活成功的调试日志。
 *   第 3 行: 使用 ctx.effect 登记生命周期清理函数，当插件卸载或重载时执行。
 *   第 4 行: 在返回的 Disposer 中打印注销日志，确保无资源悬挂。
 * 
 * 🎯 为什么这样写:
 *   遵循 DeepSeek Harness 官方插件契约，所有资源通过 ctx.effect 托管，
 *   保证热插拔和卸载时能够干净清理，绝不残留未注销的句柄。
 * 
 * @param {import('@deepseek-ai/cordis').Context} ctx 宿主上下文
 * @param {object} 配置_选项 插件配置
 */
export function apply(ctx, 配置_选项) {
  打印_调试日志("宿主半体正在激活...");

  ctx.effect(() => {
    打印_调试日志("宿主服务效果已挂载完成 ✔️");

    // 💡 返回清理闭包，由 Cordis 框架在插件卸载时统一调用
    return () => {
      打印_调试日志("宿主服务正在注销清理 🗑️");
    };
  });
}
